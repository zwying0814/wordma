export type ThemeTemplateOptions = {
  id: string;
  displayName: string;
};

function lines(items: string[]): string {
  return `${items.join('\n')}\n`;
}

function rootLayout(): string {
  return lines([
    "import type { CSSProperties, ReactNode } from 'react';",
    '',
    'import {',
    '  WordmaBodyEnd,',
    '  WordmaHead,',
    '  WordmaSeo,',
    "} from '@wordma/theme';",
    "import type { PageContext } from '@wordma/theme';",
    '',
    'type RootLayoutProps = PageContext & {',
    '  children?: ReactNode;',
    '};',
    '',
    'export function RootLayout({',
    '  site,',
    '  seo,',
    '  helpers,',
    '  children,',
    '}: RootLayoutProps) {',
    '  return (',
    '    <html lang={site.language}>',
    '      <head>',
    '        <meta charSet="utf-8" />',
    '        <meta',
    '          name="viewport"',
    '          content="width=device-width, initial-scale=1"',
    '        />',
    '        <WordmaSeo seo={seo} />',
    '        <WordmaHead />',
    '      </head>',
    '      <body',
    '        style={',
    '          {',
    "            '--theme-accent': '#3563d9',",
    '          } as CSSProperties',
    '        }',
    '      >',
    '        <header className="site-header">',
    '          <a className="site-title" href={helpers.url("/")}>',
    '            {site.title}',
    '          </a>',
    '        </header>',
    '        <main className="site-main">{children}</main>',
    '        <WordmaBodyEnd />',
    '      </body>',
    '    </html>',
    '  );',
    '}',
  ]);
}

function indexLayout(): string {
  return lines([
    "import type { PageContext } from '@wordma/theme';",
    '',
    'export function IndexLayout({',
    '  page,',
    '  collections,',
    '  helpers,',
    '}: PageContext) {',
    '  return (',
    '    <section>',
    '      <h1>{page.title}</h1>',
    '      {collections.posts.length === 0 ? (',
    '        <p>还没有文章。</p>',
    '      ) : (',
    '        <ul className="post-list">',
    '          {collections.posts.map((post) => (',
    '            <li key={post.id}>',
    '              <a href={helpers.url(post.url ?? "#")}>',
    '                {post.title}',
    '              </a>',
    '              {post.date && (',
    '                <time dateTime={post.date}>{post.date}</time>',
    '              )}',
    '            </li>',
    '          ))}',
    '        </ul>',
    '      )}',
    '    </section>',
    '  );',
    '}',
  ]);
}

function articleLayout(name: string): string {
  return lines([
    "import type { PageContext } from '@wordma/theme';",
    '',
    `export function ${name}({`,
    '  page,',
    '  content,',
    '}: PageContext) {',
    '  return (',
    '    <article className="prose">',
    '      <h1>{page.title}</h1>',
    '      {page.date && (',
    '        <time dateTime={page.date}>{page.date}</time>',
    '      )}',
    '      <div',
    '        dangerouslySetInnerHTML={{ __html: content.html }}',
    '      />',
    '    </article>',
    '  );',
    '}',
  ]);
}

function notFoundLayout(): string {
  return lines([
    "import type { PageContext } from '@wordma/theme';",
    '',
    'export function NotFoundLayout({',
    '  site,',
    '  helpers,',
    '}: PageContext) {',
    '  return (',
    '    <section className="not-found">',
    '      <h1>404</h1>',
    '      <p>页面不存在。</p>',
    '      <a href={helpers.url("/")}>返回 {site.title}</a>',
    '    </section>',
    '  );',
    '}',
  ]);
}

