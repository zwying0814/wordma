//! 笔记空间（space）能力：空间列表与应用库。
//!
//! **整个应用只有一个库**：`<app_config_dir>/wordma.db`。空间不再是独立文件，
//! 只是库里 `spaces` 表的一行；文章靠 `space_id` 归属到某个空间。
//! 所以「切换空间」是一次 `SELECT`，不存在「找不到空间文件」这种状态。
//!
//! 模块分工：
//!  - [`db`]：应用库的建库、打开（**表结构在这里**）
//!  - [`store`]：`spaces` 表的读写，纯数据库操作、不碰文件系统
//!  - [`commands`]：对外命令；名称校验在这一层
//!
//! 历史版本（文件夹空间 / 单库空间 / 旧注册表）的迁移支持已移除，
//! 不再提供从旧版 wordma 导入的任何路径。

